/**
 * Swift `Codable` types for the serial descriptors of [roots] and every class and
 * enum they reach, in the order they are reached. A class `IosX` is `X` in Swift;
 * an enum keeps its name, its cases lower camel case over the Kotlin names.
 */
@OptIn(ExperimentalSerializationApi::class)
private class SwiftTypes(roots: List<SerialDescriptor>) {
    private val types = linkedMapOf<String, SerialDescriptor>()

    init {
        roots.forEach(::visit)
    }

    private fun name(d: SerialDescriptor) = d.serialName.removeSuffix("?").substringAfterLast('.').removePrefix("Ios")

    private fun visit(d: SerialDescriptor) {
        when (d.kind) {
            StructureKind.CLASS -> if (types.putIfAbsent(name(d), d) == null) d.elementDescriptors.forEach(::visit)
            StructureKind.LIST -> visit(d.getElementDescriptor(0))
            SerialKind.ENUM -> types.putIfAbsent(name(d), d)
            is PrimitiveKind -> Unit
            else -> error("no Swift type for ${d.serialName} (${d.kind})")
        }
    }

    private fun type(d: SerialDescriptor): String {
        val base = when (d.kind) {
            PrimitiveKind.STRING -> "String"
            PrimitiveKind.INT -> "Int"
            PrimitiveKind.LONG -> "Int64"
            PrimitiveKind.BOOLEAN -> "Bool"
            PrimitiveKind.FLOAT, PrimitiveKind.DOUBLE -> "Double"
            StructureKind.LIST -> "[" + type(d.getElementDescriptor(0)) + "]"
            StructureKind.CLASS, SerialKind.ENUM -> name(d)
            else -> error("no Swift type for ${d.serialName} (${d.kind})")
        }
        return if (d.isNullable) "$base?" else base
    }

    fun source(header: String) = buildString {
        append("// ").append(header).append('\n')
        append("// From android/lollop's widget/IosSurfacePayload.kt: what the app hands the widget extension.\n\n")
        append("import Foundation\n\n")
        append("/// The widget payload format this build writes and reads; a file of another version reads as missing.\n")
        append("let widgetPayloadVersion = ").append(IOS_WIDGET_PAYLOAD_VERSION).append("\n")
        for ((name, d) in types) {
            append('\n')
            if (d.kind == SerialKind.ENUM) {
                append("enum ").append(name).append(": String, Codable, Hashable, CaseIterable {\n")
                for (i in 0 until d.elementsCount) {
                    val case = d.getElementName(i)
                    append("    case ").append(case.replaceFirstChar(Char::lowercaseChar)).append(" = \"").append(case).append("\"\n")
                }
            } else {
                append("struct ").append(name).append(": Codable, Hashable {\n")
                for (i in 0 until d.elementsCount) {
                    append("    var ").append(d.getElementName(i)).append(": ").append(type(d.getElementDescriptor(i))).append('\n')
                }
            }
            append("}\n")
        }
    }
}
