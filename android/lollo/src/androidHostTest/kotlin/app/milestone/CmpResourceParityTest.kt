package app.milestone

import android.content.Context
import androidx.test.core.app.ApplicationProvider
import app.milestone.resources.Res
import app.milestone.resources.allPluralStringResources
import app.milestone.resources.allStringArrayResources
import app.milestone.resources.allStringResources
import kotlinx.coroutines.runBlocking
import org.jetbrains.compose.resources.ExperimentalResourceApi
import org.jetbrains.compose.resources.getPluralString
import org.jetbrains.compose.resources.getString
import org.jetbrains.compose.resources.getStringArray
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner

/**
 * The Compose Multiplatform strings (`Res`, generated by `:lollo:generateComposeResources`
 * from `res/values/strings*.xml`) read exactly like the Android resources: the same
 * names, and every string, plural quantity and array item the same text through CMP's
 * `getString` / `getPluralString` / `getStringArray` as through Android's
 * `getString` / `getQuantityString` / `getStringArray`.
 *
 * A string with format arguments is compared formatted (the app never shows it
 * raw), with an argument per index: a string full of quotes, apostrophes and
 * non-ASCII for `%s`, an integer for `%d` (the quantity for a plural's first one).
 * Any other string is compared as read without arguments.
 */
@RunWith(RobolectricTestRunner::class)
@OptIn(ExperimentalResourceApi::class)
class CmpResourceParityTest {
    private val ctx: Context = ApplicationProvider.getApplicationContext()
    private val res = ctx.resources

    /** `%N$d` / `%N$s` and bare `%d` / `%s` (numbered in order, as java.util.Formatter does). */
    private val arg = Regex("""%(?:(\d+)\$)?([ds])""")

    private fun argsFor(template: String, quantity: Int? = null): Array<Any> {
        val conversions = sortedMapOf<Int, Char>()
        var ordinary = 0
        for (m in arg.findAll(template)) {
            val index = m.groupValues[1].toIntOrNull() ?: ++ordinary
            conversions.putIfAbsent(index, m.groupValues[2].single())
        }
        val count = conversions.keys.maxOrNull() ?: 0
        return Array(count) { i ->
            when (conversions[i + 1]) {
                'd' -> if (i == 0 && quantity != null) quantity else 12345
                else -> "Rock \"n\" Roll’s O'Neil ½ <&>"
            }
        }
    }

    private fun id(name: String, type: String): Int =
        res.getIdentifier(name, type, ctx.packageName).also { check(it != 0) { "no $type $name" } }

    private fun names(type: Class<*>): Set<String> = type.fields.map { it.name }.toSortedSet()

    private fun report(kind: String, compared: Int, mismatches: List<String>) =
        assertTrue(
            "${mismatches.size} of $compared $kind read differently through CMP:\n" + mismatches.joinToString("\n"),
            mismatches.isEmpty(),
        )

    private fun mismatch(what: String, android: Any, cmp: Any) = "$what\n  android: «$android»\n  cmp:     «$cmp»"

    @Test
    fun everyAndroidStringPluralAndArrayHasACmpTwin() {
        // Non-transitive R: app.milestone.R lists only this module's own resources.
        assertEquals(names(R.string::class.java), Res.allStringResources.keys.toSortedSet())
        assertEquals(names(R.plurals::class.java), Res.allPluralStringResources.keys.toSortedSet())
        assertEquals(names(R.array::class.java), Res.allStringArrayResources.keys.toSortedSet())
    }

    /** The handles common code passes outside composition (Strings.kt) read the
     *  Android resource of the same name: the generated key → R id map is complete
     *  and points at the right ids. */
    @Test
    fun everyHandleReadsItsAndroidResource() {
        val mismatches = Res.allStringResources.mapNotNull { (name, resource) ->
            val android = res.getString(id(name, "string"))
            val viaHandle = res.getString(resource)
            if (android == viaHandle) null else mismatch("string $name", android, viaHandle)
        } + Res.allPluralStringResources.mapNotNull { (name, resource) ->
            val android = res.getQuantityString(id(name, "plurals"), 2)
            val viaHandle = res.getQuantityString(resource, 2)
            if (android == viaHandle) null else mismatch("plural $name", android, viaHandle)
        } + Res.allStringArrayResources.mapNotNull { (name, resource) ->
            val android = res.getStringArray(id(name, "array")).toList()
            val viaHandle = res.getStringArray(resource)
            if (android == viaHandle) null else mismatch("array $name", android, viaHandle)
        }
        report("handles", Res.allStringResources.size + Res.allPluralStringResources.size + Res.allStringArrayResources.size, mismatches)
    }

    @Test
    fun everyStringReadsTheSame() = runBlocking {
        val strings = Res.allStringResources.toSortedMap()
        val mismatches = strings.mapNotNull { (name, resource) ->
            val id = id(name, "string")
            val args = argsFor(res.getString(id))
            val android = if (args.isEmpty()) res.getString(id) else res.getString(id, *args)
            val cmp = getString(resource, *args)
            if (android == cmp) null else mismatch("string $name args=${args.toList()}", android, cmp)
        }
        report("strings", strings.size, mismatches)
    }

    @Test
    fun everyPluralQuantityReadsTheSame() = runBlocking {
        val plurals = Res.allPluralStringResources.toSortedMap()
        var compared = 0
        val mismatches = plurals.flatMap { (name, resource) ->
            val id = id(name, "plurals")
            listOf(0, 1, 2, 5, 21, 100).mapNotNull { q ->
                compared++
                val args = argsFor(res.getQuantityText(id, q).toString(), quantity = q)
                val android = if (args.isEmpty()) res.getQuantityString(id, q) else res.getQuantityString(id, q, *args)
                val cmp = getPluralString(resource, q, *args)
                if (android == cmp) null else mismatch("plural $name q=$q args=${args.toList()}", android, cmp)
            }
        }
        report("plural quantities", compared, mismatches)
    }

    @Test
    fun everyStringArrayReadsTheSame() = runBlocking {
        val arrays = Res.allStringArrayResources.toSortedMap()
        val mismatches = arrays.mapNotNull { (name, resource) ->
            val android = res.getStringArray(id(name, "array")).toList()
            val cmp = getStringArray(resource)
            if (android == cmp) null else mismatch("array $name", android, cmp)
        }
        report("arrays", arrays.size, mismatches)
    }
}
