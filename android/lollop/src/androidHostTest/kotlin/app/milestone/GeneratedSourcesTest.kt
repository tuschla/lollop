/**
 * The files generated from Kotlin for what can't reference it: the iOS widget
 * extension's payload types, design tokens, strings, fallback faces and test
 * fixture, the launch grounds of both apps, and make-assets.py's icon list. Each
 * test fails when its committed file differs from what the Kotlin gives now;
 * regenerate them all with
 *
 *     LOLLOP_WRITE_GENERATED=1 ./gradlew :lollop:testAndroidHostTest --tests app.milestone.GeneratedSourcesTest --rerun
 *
 * The unit-test working directory is the lollop module.
 */
@RunWith(RobolectricTestRunner::class)
class GeneratedSourcesTest {
    private val ctx get() = ApplicationProvider.getApplicationContext<Context>()
    private val res get() = ctx.resources
    private val ios = File("../../iosApp")
    private val write = System.getenv("LOLLOP_WRITE_GENERATED") == "1"
    private val header = "Generated by android/lollop's GeneratedSourcesTest. Do not edit."
    private lateinit var locale: Locale

    @Before
    fun englishUs() {
        locale = Locale.getDefault()
        Locale.setDefault(Locale.US)
    }

    @After
    fun restoreLocale() = Locale.setDefault(locale)

    private fun check(file: File, text: String) {
        if (write) {
            file.parentFile.mkdirs()
            file.writeText(text)
            return
        }
        assertEquals("${file.path} is generated: run GeneratedSourcesTest with LOLLOP_WRITE_GENERATED=1 (see its doc)", text, file.readText())
    }

    @OptIn(ExperimentalSerializationApi::class)
    private val pretty = Json {
        encodeDefaults = true
        prettyPrint = true
        prettyPrintIndent = "  "
    }

    private fun <T> json(serializer: KSerializer<T>, value: T) = pretty.encodeToString(serializer, value) + "\n"

    // ── iOS widget extension: payload types, fallback, fixture ──────────────

    @Test
    fun swiftPayloadTypes() {
        val roots = listOf(IosWidgetPayload.serializer(), IosWidgetFallback.serializer(), IosRunLive.serializer(), IosRestLive.serializer())
        check(File(ios, "Shared/SurfacePayload.swift"), SwiftTypes(roots.map { it.descriptor }).source(header))
    }

    @Test
    fun fallbackFaces() = check(File(ios, "LollopWidgets/fallback.json"), json(IosWidgetFallback.serializer(), iosWidgetFallback(res)))

    /** What the Swift tests read: the widget payload of every state of Android's
     *  widget screenshots ([WidgetFixtures]), run frames and a rest. */
    @Serializable
    private data class IosFixture(val widgets: Map<String, IosWidgetPayload>, val runs: Map<String, IosRunLive>, val rest: IosRestLive)

    @Test
    fun swiftTestFixture() {
        val theme = AppTheme.Default
        val widgets = WidgetFixtures.states(res).mapValues { (_, s) -> iosWidgetPayload(s.snapshot, s.recording, theme, DarkMode.System, res) }
        fun run(phase: RunSurfacePhase, hasTrack: Boolean = true) =
            runLiveOf(RunSurfaceState(phase, movingSec = 1421, distanceKm = 4.12, paceMinPerKm = 5.75, miles = false, hasTrack = hasTrack), theme, res)
        val runs = linkedMapOf(
            "recording" to run(RunSurfacePhase.Recording),
            "paused" to run(RunSurfacePhase.Paused),
            "locating" to run(RunSurfacePhase.Locating, hasTrack = false),
        )
        val start = 1_761_690_000_000L
        val rest = restLiveOf(RestRun(start, start + 90_000L, "Back squat"), RestNextSet("Back squat", "Set 3 of 4 · 100 kg × 5"), theme, res)
        check(File(ios, "LollopWidgetsTests/fixtures.json"), json(IosFixture.serializer(), IosFixture(widgets, runs, rest)))
    }

    // ── iOS widget extension: design tokens ─────────────────────────────────

    /** The iOS text style whose default size is nearest [sp] (ties: the larger),
     *  so the widgets follow the reader's text size from Theme.kt's scale. */
    private fun textStyle(sp: Float): String = listOf(
        "largeTitle" to 34, "title" to 28, "title2" to 22, "title3" to 20, "body" to 17,
        "callout" to 16, "subheadline" to 15, "footnote" to 13, "caption" to 12, "caption2" to 11,
    ).minWith(compareBy<Pair<String, Int>> { kotlin.math.abs(it.second - sp) }.thenByDescending { it.second }).first

    private fun font(style: TextStyle): String = buildString {
        append("Font.system(.").append(textStyle(style.fontSize.value)).append(')')
        when (style.fontWeight ?: FontWeight.Normal) {
            FontWeight.Normal -> Unit
            FontWeight.Medium -> append(".weight(.medium)")
            FontWeight.SemiBold -> append(".weight(.semibold)")
            FontWeight.Bold -> append(".weight(.bold)")
            FontWeight.ExtraBold -> append(".weight(.heavy)")
            FontWeight.Black -> append(".weight(.black)")
            else -> error("no iOS weight for ${style.fontWeight}")
        }
        if (style.fontFeatureSettings?.contains("tnum") == true) append(".monospacedDigit()")
    }

    @Test
    fun swiftWidgetTheme() {
        val fonts = linkedMapOf(
            "display" to Type.Display,
            "title" to Type.Title,
            "body" to Type.Body,
            "bodyBold" to Type.BodyBold,
            "caption" to Type.Caption,
            "overline" to Type.Overline,
            "overlineRegular" to Type.Overline.copy(fontWeight = FontWeight.Normal),
            "chip" to Type.Chip,
        )
        val source = buildString {
            append("// ").append(header).append('\n')
            append("// From Theme.kt's Type and Space: each type token in the iOS text style nearest its size.\n\n")
            append("import SwiftUI\n\n")
            append("enum WidgetType {\n")
            for ((name, style) in fonts) append("    static let ").append(name).append(" = ").append(font(style)).append('\n')
            append("    static let overlineTracking: CGFloat = ").append(Type.Overline.letterSpacing.value).append('\n')
            append("}\n\n")
            append("enum WidgetSpace {\n")
            for ((name, dp) in listOf("sm" to Space.Sm, "md" to Space.Md, "screen" to Space.Screen)) {
                append("    static let ").append(name).append(": CGFloat = ").append(dp).append('\n')
            }
            append("}\n")
        }
        check(File(ios, "LollopWidgets/WidgetTheme.swift"), source)
    }

    // ── iOS strings ─────────────────────────────────────────────────────────

    /** The string resources the Swift side names by key (widget and control
     *  metadata, the App Intents), in the Localizable.strings of the app and the extension. */
    private val swiftStringKeys = listOf(
        "widget_overline_today", "widget_description", "tile_log", "tile_log_set", "ios_control_description",
        "ios_intent_open_title", "ios_intent_open_screen", "ios_intent_screen_type", "ios_intent_pause_title",
        "ios_intent_paused", "main_dest_today", "main_log", "main_plan_item_track",
    )

    private fun stringsLiteral(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n") + "\""

    @Test
    fun swiftStrings() {
        val source = buildString {
            append("/* ").append(header).append(" From res/values/strings*.xml. */\n\n")
            for (key in swiftStringKeys.sorted()) {
                append(stringsLiteral(key)).append(" = ").append(stringsLiteral(res.getString(androidStringId(key)))).append(";\n")
            }
        }
        check(File(ios, "Shared/en.lproj/Localizable.strings"), source)
    }

    /** Every resource key a Swift source names is in the generated table, and every
     *  key in the table is named. */
    @Test
    fun swiftNamesOnlyGeneratedStrings() {
        val key = Regex("\"((?:widget|tile|main|ios)_[a-z0-9_]+)\"")
        val named = listOf("iosApp", "Shared", "LollopWidgets").flatMap { dir ->
            File(ios, dir).walkTopDown().filter { it.isFile && it.extension == "swift" }.toList()
        }.flatMap { f -> key.findAll(f.readText()).map { it.groupValues[1] }.toList() }.toSet()
        assertEquals(swiftStringKeys.toSet(), named)
    }

